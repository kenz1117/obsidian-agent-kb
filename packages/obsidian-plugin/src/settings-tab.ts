import { App, PluginSettingTab, Setting } from 'obsidian';
import ObsidianAgentKbPlugin from './main';
import { OakbSettings } from './types';

export class OakbSettingTab extends PluginSettingTab {
  private plugin: ObsidianAgentKbPlugin;

  constructor(app: App, plugin: ObsidianAgentKbPlugin) {
    super(app, plugin);
    this.plugin = plugin;
  }

  display(): void {
    const { containerEl } = this;
    containerEl.empty();
    containerEl.createEl('h2', { text: 'Obsidian Agent KB' });

    const fields: Array<[keyof OakbSettings, string, string]> = [
      ['knowledgeRoot', 'Knowledge root', 'Governed knowledge folder.'],
      ['autoFolder', 'Auto folder', 'Subfolder generated by agents.'],
      ['reviewedFolder', 'Review folder', 'Subfolder awaiting review.'],
      ['canonicalFolder', 'Canonical folder', 'Trusted knowledge folder.'],
      ['archiveRoot', 'Archive root', 'Destination for rejected or stale cards.'],
      ['reviewer', 'Reviewer', 'Name written to review_by.']
    ];

    for (const [key, name, description] of fields) {
      new Setting(containerEl)
        .setName(name)
        .setDesc(description)
        .addText(text => text
          .setValue(String(this.plugin.settings[key]))
          .onChange(async value => {
            (this.plugin.settings as any)[key] = value;
            await this.plugin.saveSettings();
          }));
    }

    new Setting(containerEl)
      .setName('Stale after days')
      .setDesc('Cards older than this appear in the Stale queue.')
      .addText(text => text
        .setValue(String(this.plugin.settings.staleDays))
        .onChange(async value => {
          const parsed = Number(value);
          this.plugin.settings.staleDays = Number.isFinite(parsed) && parsed > 0 ? parsed : 180;
          await this.plugin.saveSettings();
        }));

    new Setting(containerEl)
      .setName('Show governance scores')
      .setDesc('Display governance_score on review cards.')
      .addToggle(toggle => toggle
        .setValue(this.plugin.settings.showScores)
        .onChange(async value => {
          this.plugin.settings.showScores = value;
          await this.plugin.saveSettings();
        }));
  }
}
