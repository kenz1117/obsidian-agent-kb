export type MessageKey = keyof typeof dictionaries.zh;

export function setLocale(value: Locale): void {
  locale = value === 'en' ? 'en' : 'zh';
}

export function t(key: MessageKey, args?: any): string {
  const template = dictionaries[locale][key];
  return typeof template === 'function' ? template(args) : template;
}

const STATUS_LABELS: Record<string, { zh: string; en: string }> = {
  auto: { zh: '自动生成', en: 'Auto' },
  pending: { zh: '待处理', en: 'Pending' },
  review: { zh: '待审阅', en: 'Review' },
  canonical: { zh: '正式知识', en: 'Canonical' },
  archive: { zh: '已归档', en: 'Archived' },
  archived: { zh: '已归档', en: 'Archived' }
};

/** Localised label for a frontmatter status value, falling back to raw text. */
export function tStatus(status: string): string {
  const known = STATUS_LABELS[status];
  if (!known) return status;
  return locale === 'en' ? known.en : known.zh;
}
